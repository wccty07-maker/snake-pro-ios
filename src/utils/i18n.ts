export const getLocalizedAchievement = (
  achievement: { id: string; title: string; description: string },
  lang: SupportedLanguage = 'zh-HK'
): { title: string; description: string } => {
  const item = LOCALIZED_ACHIEVEMENTS[achievement.id]?.[lang];
  if (item) {
    return item;
  }
  return {
    title: lang === 'zh-CN' ? toSimplifiedChinese(achievement.title) : achievement.title,
    description: lang === 'zh-CN' ? toSimplifiedChinese(achievement.description) : achievement.description,
  };
};

export function getCopyUrlText(lang: SupportedLanguage = 'zh-HK', isCopied: boolean = false): string {
  if (isCopied) {
    switch (lang) {
      case 'zh-CN':
        return '已复制!';
      case 'en':
        return 'Copied!';
      case 'ja':
        return 'コピー完了!';
      default:
        return '已複製!';
    }
  }
  switch (lang) {
    case 'zh-CN':
      return '复制网址';
    case 'en':
      return 'Copy URL';
    case 'ja':
      return 'URLをコピー';
    default:
      return '複製網址';
  }
}

