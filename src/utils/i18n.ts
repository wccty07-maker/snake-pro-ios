// Localized Daily Rewards Labels
export const getLocalizedDailyRewardLabel = (
  day: number,
  coins: number,
  hearts: number,
  lang: SupportedLanguage = 'zh-HK'
): string => {
  if (lang === 'en') {
    if (coins > 0 && hearts > 0) return `${coins} Coins + ${hearts} Hearts`;
    if (coins > 0) return `${coins} Coins`;
    return `${hearts} ${hearts > 1 ? 'Hearts' : 'Heart'}`;
  }
  if (lang === 'ja') {
    if (coins > 0 && hearts > 0) return `${coins}コイン + ハート${hearts}個`;
    if (coins > 0) return `${coins} コイン`;
    return `ハート ${hearts}個`;
  }
  if (lang === 'zh-CN') {
    if (coins > 0 && hearts > 0) return `${coins}金币 + ${hearts}爱心`;
    if (coins > 0) return `${coins} 金币`;
    return `${hearts} 颗爱心`;
  }
  if (coins > 0 && hearts > 0) return `${coins}金幣 + ${hearts}愛心`;
  if (coins > 0) return `${coins} 金幣`;
  return `${hearts} 顆愛心`;
};

