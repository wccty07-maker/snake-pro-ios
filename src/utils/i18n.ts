export const LOCALIZED_DAILY_MISSIONS = LOCALIZED_MISSIONS;

export const getLocalizedDailyMission = (
  mission: { id: string; title: string; description: string; maxProgress: number },
  lang: SupportedLanguage = 'zh-HK'
): { title: string; description: string } => {
  // Extract base prefix e.g. "daily_play_lvl3" -> "daily_play" or "daily_play_2"
  const prefix = mission.id.replace(/_lvl\d+$/, '');
  const template =
    LOCALIZED_MISSIONS[mission.id]?.[lang] ||
    LOCALIZED_MISSIONS[prefix]?.[lang] ||
    (prefix === 'daily_play' ? LOCALIZED_MISSIONS['daily_play_2']?.[lang] : undefined) ||
    (prefix === 'daily_eat' ? LOCALIZED_MISSIONS['daily_eat_20']?.[lang] : undefined) ||
    (prefix === 'daily_score' ? LOCALIZED_MISSIONS['daily_score_150']?.[lang] : undefined) ||
    (prefix === 'daily_level' ? LOCALIZED_MISSIONS['daily_level_1']?.[lang] : undefined) ||
    (prefix === 'daily_coins' ? LOCALIZED_MISSIONS['daily_earn_coins']?.[lang] : undefined);

  if (template) {
    return {
      title: template.title,
      description: template.description.replace('{n}', String(mission.maxProgress)),
    };
  }

  const fallbackDesc = mission.description.replace('{n}', String(mission.maxProgress));
  return {
    title: lang === 'zh-CN' ? toSimplifiedChinese(mission.title) : mission.title,
    description: lang === 'zh-CN' ? toSimplifiedChinese(fallbackDesc) : fallbackDesc,
  };
};

