/**
 * 自動偵測玩家手機或瀏覽器之系統語言 (Auto-detect user device system language)
 * - 日本語 (ja, ja-JP...) -> 'ja'
 * - 簡體中文 (zh-CN, zh-Hans, zh-SG...) -> 'zh-CN'
 * - 繁體中文 (zh-HK, zh-TW, zh-Hant, zh-MO...) -> 'zh-HK'
 * - 英文及其他歐美非中日語系 (en, fr, de, es...) -> 'en'
 * - 無法判斷或伺服器環境時默認 -> 'zh-HK'
 */
export function detectSystemLanguage(): SupportedLanguage {
  try {
    if (typeof window === 'undefined' || !window.navigator) {
      return 'zh-HK';
    }

    const navLanguages: readonly string[] =
      window.navigator.languages && window.navigator.languages.length > 0
        ? window.navigator.languages
        : [window.navigator.language || ''];

    for (const raw of navLanguages) {
      if (!raw) continue;
      const l = raw.toLowerCase().trim();

      // 日本語
      if (l.startsWith('ja')) {
        return 'ja';
      }

      // 簡體中文
      if (
        l.includes('hans') ||
        l === 'zh-cn' ||
        l === 'zh-sg' ||
        l === 'zh-my'
      ) {
        return 'zh-CN';
      }

      // 繁體中文
      if (
        l.includes('hant') ||
        l === 'zh-hk' ||
        l === 'zh-tw' ||
        l === 'zh-mo'
      ) {
        return 'zh-HK';
      }

      // 泛中文若無註明則偏向繁體中文
      if (l.startsWith('zh')) {
        return 'zh-HK';
      }

      // 英文
      if (l.startsWith('en')) {
        return 'en';
      }
    }

    // 若為其他外語（如法文、德文、西班牙文、韓文等），國際通用首選英文
    const primary = (window.navigator.language || '').toLowerCase().trim();
    if (primary) {
      if (primary.startsWith('ja')) return 'ja';
      if (primary.startsWith('zh')) {
        return primary.includes('cn') || primary.includes('hans') ? 'zh-CN' : 'zh-HK';
      }
      return 'en';
    }
  } catch {
    // fallback if navigator is restricted
  }

  return 'zh-HK';
}

