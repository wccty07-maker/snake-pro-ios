/**
 * Convert any string containing Traditional Chinese characters or phrases into Simplified Chinese.
 */
export function toSimplifiedChinese(input: string): string {
  if (!input) return input;

  // 1. First replace multi-character phrases
  let output = input;
  for (const [regex, replacement] of PHRASE_REPLACEMENTS) {
    output = output.replace(regex, replacement);
  }

  // 2. Character-by-character replacement
  let result = '';
  for (let i = 0; i < output.length; i++) {
    const ch = output[i];
    result += T2S_MAP[ch] || ch;
  }

  return result;
}
